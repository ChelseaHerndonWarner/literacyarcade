// Validates word-forge-bank.js and writes a reviewable sheet.
//   node tools/word-forge/validate-bank.js
// Exits non-zero if any rule fails. The dictionary column is only a hint (macOS /usr/share/dict/web2 if
// present); a dictionary hit is NOT proof of a correct morphological analysis.
const fs = require('fs');
const path = require('path');
const bank = require('../../word-forge-bank.js');
let excluded = {};
try { excluded = require('./excluded.json'); } catch (e) { /* optional */ }

const errors = [];
const warnings = [];
const err = (m) => errors.push(m);
const byId = new Map(bank.parts.map((p) => [p.id, p]));
if (byId.size !== bank.parts.length) err('duplicate part ids');
bank.parts.forEach((p) => {
  if (p.text !== p.id) err(`part ${p.id}: text must equal id for now`);
  if (!['prefix', 'root', 'suffix'].includes(p.type)) err(`part ${p.id}: bad type ${p.type}`);
  const okKind = { prefix: ['derivational'], root: ['base'], suffix: ['derivational', 'inflectional'] }[p.type] || [];
  if (!okKind.includes(p.kind)) err(`part ${p.id}: kind "${p.kind}" is not valid for a ${p.type}`);
});

// ── word rules ──
const seenWords = new Set();
const seenSeq = new Map();
for (const w of bank.words) {
  if (seenWords.has(w.w)) err(`duplicate word ${w.w}`);
  seenWords.add(w.w);
  const key = w.parts.join('|');
  if (seenSeq.has(key)) err(`${w.w}: same part sequence as ${seenSeq.get(key)}`);
  seenSeq.set(key, w.w);
  if (w.parts.length < 2) err(`${w.w}: needs at least 2 parts`);
  if (excluded[w.w]) err(`${w.w}: is on the excluded list (${excluded[w.w]})`);
  const missing = w.parts.filter((id) => !byId.has(id));
  if (missing.length) { err(`${w.w}: unknown parts ${missing.join(',')}`); continue; }
  const joined = w.parts.map((id) => byId.get(id).text).join('');
  if (joined !== w.w) err(`${w.w}: parts join to "${joined}" (spelling change not allowed)`);
  const types = w.parts.map((id) => byId.get(id).type);
  const rootCount = types.filter((t) => t === 'root').length;
  const order = types.map((t) => ({ prefix: 0, root: 1, suffix: 2 }[t]));
  if (rootCount !== 1) err(`${w.w}: needs exactly one root (has ${rootCount})`);
  if (order.some((n, i) => i > 0 && n < order[i - 1])) err(`${w.w}: parts out of order (prefix → root → suffix)`);
  const kinds = w.parts.map((id) => byId.get(id).kind);
  const firstInfl = kinds.indexOf('inflectional');
  if (firstInfl >= 0 && kinds.slice(firstInfl).some((k) => k === 'derivational' || k === 'base')) err(`${w.w}: a derivational part follows an inflectional ending`);
  const root = byId.get(w.parts.find((id) => byId.get(id).type === 'root'));
  if (root && root.free === false && w.parts.length === 2 && types[0] === 'root') err(`${w.w}: bound root "${root.id}" cannot stand with only an ending`);
  if (!(w.level >= 1 && w.level <= 4)) err(`${w.w}: level must be 1-4`);
}

// ── recipes: computed valid words ──
const VAULTS = ['builders', 'changers', 'chains', 'masters'];
const recipeInfo = [];
const vaultWords = Object.fromEntries(VAULTS.map((v) => [v, new Set()]));
for (const r of bank.recipes) {
  const bad = r.parts.filter((id) => !byId.has(id));
  if (bad.length) { err(`recipe ${r.id}: unknown parts ${bad.join(',')}`); continue; }
  if (!VAULTS.includes(r.vault)) err(`recipe ${r.id}: unknown vault ${r.vault}`);
  if (r.parts.length > 14) err(`recipe ${r.id}: ${r.parts.length} runes is too many`);
  const set = new Set(r.parts);
  const valid = bank.words.filter((w) => w.parts.every((id) => set.has(id)));
  if (valid.length < r.minWords) err(`recipe ${r.id}: only ${valid.length} valid words (sanity floor ${r.minWords}; word counts are never padded to hit a target)`);
  const usedParts = new Map();
  valid.forEach((w) => w.parts.forEach((id) => usedParts.set(id, (usedParts.get(id) || 0) + 1)));
  const weak = r.parts.filter((id) => (usedParts.get(id) || 0) < 2);
  if (weak.length) warnings.push(`recipe ${r.id}: runes that build fewer than 2 words (mostly distractors): ${weak.join(', ')}`);
  const long = valid.filter((w) => w.w.length >= 8).length;
  valid.forEach((w) => vaultWords[r.vault] && vaultWords[r.vault].add(w.w));
  recipeInfo.push({ r, valid, long, weak });
}

let web2 = null;
try { web2 = new Set(fs.readFileSync('/usr/share/dict/web2', 'latin1').split('\n')); } catch (e) { /* optional */ }
const SUF = ['ness', 'less', 'ful', 'ing', 'ed', 'er', 'es', 's', 'ly', 'ment', 'ion', 'ation'];
function dictHint(word) {
  if (!web2) return '?';
  if (web2.has(word)) return 'yes';
  for (const s of SUF) if (word.endsWith(s) && web2.has(word.slice(0, -s.length))) return 'derived';
  return 'no';
}

// ── review sheet ──
const L = [];
L.push('# Word Forge word bank — draft for review', '');
L.push('Generated by `tools/word-forge/validate-bank.js`. **Not used by the game yet.**', '');
L.push('Every word is exactly its parts joined with no spelling change. ⚑ = ambiguous or uncommon, needs your yes/no. The dictionary is only a hint; it never proves the word-part analysis is right.', '');
const flagged = bank.words.filter((w) => w.review);
L.push(`**Totals:** ${bank.parts.length} parts (${bank.parts.filter((p) => p.type === 'prefix').length} prefixes, ${bank.parts.filter((p) => p.type === 'root').length} roots, ${bank.parts.filter((p) => p.type === 'suffix').length} suffixes), **${bank.words.length} words**, ${bank.recipes.length} recipes. ${flagged.length} words flagged ⚑.`, '');
L.push('## Rounds sized for the timers', '');
L.push('Word counts are not padded to reach a target. Students should enjoy and succeed in a round without finding every possible word; a strong player who does find them all gets the early-finish celebration. The only check is a floor of 15 words so a round never feels empty.', '');
L.push('| Recipe | Vault | Tier | Runes | Valid words | 8+ letter words |', '|---|---|---|---|---|---|');
for (const { r, valid, long } of recipeInfo) L.push(`| ${r.id} — ${r.title} | ${r.vault} | ${r.tier} | ${r.parts.length} | ${valid.length} | ${long} |`);
L.push('');
L.push('Distinct words by vault (union of its recipes): ' + VAULTS.map((v) => `${v} ${vaultWords[v].size}`).join(', ') + '.', '');
if (warnings.length) { L.push('**Warnings:**', ...warnings.map((w) => `- ${w}`), ''); }

L.push('## Flagged for your decision ⚑', '', '| Word | Parts | Why |', '|---|---|---|');
for (const w of flagged) L.push(`| ${w.w} | ${w.parts.join(' + ')} | ${w.note} |`);
L.push('', '## Excluded on purpose', '', '| Word | Why |', '|---|---|');
for (const [w, why] of Object.entries(excluded)) L.push(`| ${w} | ${why} |`);
L.push('');

for (const v of VAULTS) {
  L.push(`## ${v[0].toUpperCase() + v.slice(1)}`, '');
  for (const { r, valid } of recipeInfo.filter((x) => x.r.vault === v)) {
    L.push(`### ${r.id} (tier ${r.tier}) — ${r.title}`, `Runes: \`${r.parts.join(' ')}\` → **${valid.length} words**`, '');
    const byRoot = new Map();
    for (const w of valid) {
      const root = w.parts.find((id) => byId.get(id).type === 'root');
      if (!byRoot.has(root)) byRoot.set(root, []);
      byRoot.get(root).push(w);
    }
    for (const [root, ws] of byRoot) {
      L.push(`- **${root}**: ` + ws.map((w) => `${w.parts.join('+')}${w.review ? '⚑' : ''}`.replace(/^/, '')).join(' · '));
    }
    L.push('');
  }
}
const out = path.join(__dirname, 'bank-review.md');
fs.writeFileSync(out, L.join('\n'));
try { fs.unlinkSync(path.join(__dirname, 'bank-sample-review.md')); } catch (e) { /* old sample sheet */ }

console.log(`parts ${bank.parts.length} | words ${bank.words.length} | recipes ${bank.recipes.length} | flagged ${flagged.length}`);
console.log('distinct words per vault:', VAULTS.map((v) => `${v} ${vaultWords[v].size}`).join(', '));
recipeInfo.forEach(({ r, valid, long }) => console.log(`  ${r.id.padEnd(6)} ${String(r.parts.length).padStart(2)} runes ${String(valid.length).padStart(3)} words (${long} long)  min ${r.minWords}`));
warnings.forEach((w) => console.log('WARN ' + w));
console.log(errors.length ? `\n${errors.length} PROBLEM(S):\n - ` + errors.join('\n - ') : '\nall checks passed');
console.log('review sheet written to', path.relative(process.cwd(), out));
process.exit(errors.length ? 1 : 0);
